-- 예측에 **무승부** 추가
--
-- ## 왜 바꾸는가
--
-- 기존 규칙은 "승패 예측은 홈/원정 중 하나를 고르는 방식이므로 무승부면 전원 미적중"
-- 이었다(기획서 4장). 그런데 **KBO 는 무승부가 실제로 있다** — 크롤러 실측으로 3:3, 0:0 을
-- 확인했다. 무승부가 나면 그날 그 경기를 예측한 모든 유저가 아무 이유 없이 손해를 본다.
--
-- 무승부를 선택지로 주면 예측이 공정해진다. 3택(홈 / 무승부 / 원정)이 된다.
--
-- ⚠️ enum 값 추가는 **그 값을 쓰는 마이그레이션과 분리**해야 한다.
--    같은 트랜잭션에서 추가하고 사용하면 Postgres 가 거부한다.

alter type public.prediction_pick add value if not exists 'draw';
